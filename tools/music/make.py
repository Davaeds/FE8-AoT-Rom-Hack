"""Compile the AoT soundtrack (tools/music/songs/*.mml) for the build.

    python3 tools/music/make.py FE8_clean.gba build/gen

Writes build/gen/nim.bin (the General MIDI voicegroup made of FE8's own
instruments, see nim.py) and build/gen/music.event, which AoT/AoT.event
includes: song data, then the song table entries for the replaced ids.
"""
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import m4a  # noqa: E402
import mml  # noqa: E402
import nim  # noqa: E402

SONG_TABLE = 0x224470
TITLE_SONG = 0x43


def main(rom_path, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    rom = open(rom_path, "rb").read()
    table, _ = nim.build(rom)
    open(os.path.join(out_dir, "nim.bin"), "wb").write(table)
    ev = ["// Generated by tools/music/make.py. Do not edit.", "ALIGN 4", "AoT_Voicegroup:",
          '#incbin "nim.bin"']
    entries = []
    for path in sorted(glob.glob(os.path.join(HERE, "songs", "*.mml"))):
        name = os.path.splitext(os.path.basename(path))[0]
        meta, tracks = mml.parse_song(path)
        ends = {t[0]: (t[3], t[2]) for t in tracks}
        if len({e for e, _ in ends.values()}) > 1 or len({l for _, l in ends.values()}) > 1:
            raise SystemExit(f"{name}: tracks differ in length or loop point (ticks): {ends}")
        ev.append(m4a.song_event(name, meta, tracks, "AoT_Voicegroup"))
        for sid in meta["song"].split():
            entries.append((int(sid, 0), name))
    preview = os.environ.get("AOT_MUSIC_PREVIEW", "")
    if preview and not preview.startswith("0x"):  # play it on the title screen too
        entries.append((TITLE_SONG, preview))
    ev.append("PUSH")
    for sid, name in entries:
        ev.append(f"ORG 0x{SONG_TABLE:X} + 0x{sid:X} * 8")
        ev.append(f"POIN AoT_Song_{name}")
    if preview.startswith("0x"):  # a vanilla song on the title screen, for comparison
        header = int.from_bytes(rom[SONG_TABLE + int(preview, 16) * 8:][:4], "little")
        ev.append(f"ORG 0x{SONG_TABLE:X} + 0x{TITLE_SONG:X} * 8")
        ev.append(f"WORD 0x{header:X}")
    ev.append("POP")
    with open(os.path.join(out_dir, "music.event"), "w") as f:
        f.write("\n".join(ev) + "\n")
    print(f"music: {len(entries)} song slots")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
