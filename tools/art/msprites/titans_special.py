# Steam puffs around the Colossal Titan, drifting up over the idle frames.
PUFF_BIG = ('.WW.', 'WWWw', '.ww.')
PUFF_MED = ('WW', 'ww')
PUFF_DOT = ('W',)
STEAM = [
    [(PUFF_BIG, 2, 11), (PUFF_MED, 4, 8), (PUFF_BIG, 26, 12), (PUFF_MED, 27, 9), (PUFF_DOT, 6, 6), (PUFF_DOT, 25, 6)],
    [(PUFF_BIG, 2, 10), (PUFF_MED, 4, 7), (PUFF_BIG, 26, 11), (PUFF_MED, 26, 8), (PUFF_DOT, 6, 5), (PUFF_DOT, 26, 5)],
    [(PUFF_BIG, 3, 9), (PUFF_MED, 5, 6), (PUFF_BIG, 25, 10), (PUFF_MED, 26, 7), (PUFF_DOT, 7, 4), (PUFF_DOT, 26, 4)],
]


def steam(a, puffs):
    b = a.copy()
    for pat, x0, y0 in puffs:
        for dy, row in enumerate(pat):
            for dx, c in enumerate(row):
                x, y = x0 + dx, y0 + dy
                if c != '.' and 0 <= x < 32 and 0 <= y < 32 and b[y, x] == 0:
                    b[y, x] = LEGEND[c]
    return b


def armored():
    s, f, k = ARMORED_SIDE, ARMORED_FRONT, ARMORED_BACK
    walk_f = lambda a: [a, lift(bob(a, 22), 9, 15, 26, 29), a, lift(bob(a, 22), 16, 23, 26, 29)]
    left = [s, lift(bob(s, 22), 6, 15, 26, 29), s, lift(bob(s, 22), 17, 28, 26, 29)]
    return dict(sms=[s, bob(s, 22), bob(s, 22)], left=left, down=walk_f(f), up=walk_f(k),
                sel=[f, bob(f, 22), bob(f, 22)])


def colossal():
    idle = [steam(COLOSSAL, p) for p in STEAM]
    return dict(sms=idle, left=idle + idle[1:2], down=idle + idle[1:2], up=idle + idle[1:2], sel=idle)


def dummy():
    d = DUMMY
    return dict(sms=[d, d, d], left=[d] * 4, down=[d] * 4, up=[d] * 4, sel=[d] * 3)


BUILD = {'armored': armored, 'colossal': colossal, 'dummy': dummy}


def frames(name):
    return BUILD[name]()
