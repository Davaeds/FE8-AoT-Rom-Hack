"""Armored Titan, Colossal Titan and the wooden training dummy: 32x32 map sprites.

    armored   the Armored Titan (chapter 1 ending): white armor plates, blond mane,
              exposed red muscle at the joints; it charges the inner gate, so its
              walk frames (front view) are the ones players see most
    colossal  the Colossal Titan looking over Wall Maria: skinless head and
              shoulders, hands gripping the wall top, steam rising (idle frames)
    dummy     the cadets' wooden Titan dummy (chapter 2) with its leather nape target

Full 32x32 frames in the shared AoT palette slots (see pal.py); walk frames are
derived from the standing poses with bob() and lift().
"""
import numpy as np
from kit import grid
from pal import LEGEND

SHADOW = LEGEND['_']


def bob(a, split):
    """Raise the rows above `split` by one pixel; row split-1 stretches to fill the gap."""
    b = a.copy()
    b[0:split - 1] = a[1:split]
    return b


def lift(a, x0, x1, y0, y1):
    """Raise one shin and foot (columns x0..x1, rows y0..y1) by one pixel."""
    b = a.copy()
    reg = a[y0:y1 + 1, x0:x1 + 1].copy()
    blk = b[y0:y1 + 1, x0:x1 + 1]
    blk[blk != SHADOW] = 0
    ys, xs = np.nonzero((reg != 0) & (reg != SHADOW))
    b[y0 + ys - 1, x0 + xs] = reg[ys, xs]
    return b


