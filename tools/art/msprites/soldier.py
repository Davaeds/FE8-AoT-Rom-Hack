def tall(spec, row=9):
    """Hannes: one row more torso (adult height), head one row higher."""
    body, view, (x, y) = spec
    rows = body.strip('\n').split('\n')
    assert rows[0].strip('.') == '', 'top row must be empty to grow'
    rows = rows[1:row + 1] + [rows[row]] + rows[row + 1:]
    return '\n'.join(rows), view, (x, y - 1)


def _frame(name, spec, extra=None):
    body, view, at = spec
    return compose(body, HEADS[name][view], at, extra)


def frames(name):
    sets = dict(sms=SIDE_IDLE, left=SIDE_WALK, down=FRONT_WALK, up=BACK_WALK, sel=SEL)
    if name == 'hannes':
        sets = {k: [tall(s) for s in v] for k, v in sets.items()}
    return {k: [_frame(name, s) for s in v] for k, v in sets.items()}
