"""Soldier map sprites (104th cadets, Garrison): ODM gear, two blades, 16x16.

Every frame is drawn as a body (interior colours only, no outline) plus a
character head template stamped at a per-frame anchor, so a character's head
pixels never change between frames. The 1 px outline and the ground shadow are
added afterwards, like FE8 draws them.
"""
import numpy as np
from kit import grid
from pal import LEGEND

O, SH = LEGEND['o'], LEGEND['_']


# ---------------------------------------------------------------- helpers
def paint(text, w=None):
    rows = text.strip('\n').split('\n')
    w = w or max(len(r) for r in rows)
    for r in rows:
        assert len(r) <= w, (len(r), r)
    return grid('\n'.join(r.ljust(w, '.') for r in rows), w, len(rows))


def stamp(dst, src, x0, y0):
    out = dst.copy()
    h, w = src.shape
    for y in range(h):
        for x in range(w):
            if src[y, x] and 0 <= y + y0 < out.shape[0] and 0 <= x + x0 < out.shape[1]:
                out[y + y0, x + x0] = src[y, x]
    return out


def outline(a):
    """1 px outline on the outside only (4-neighbour, FE8 style)."""
    h, w = a.shape
    fill = (a != 0) & (a != SH)
    out = a.copy()
    for y in range(h):
        for x in range(w):
            if a[y, x]:
                continue
            for dy, dx in ((0, 1), (1, 0), (0, -1), (-1, 0)):
                yy, xx = y + dy, x + dx
                if 0 <= yy < h and 0 <= xx < w and fill[yy, xx]:
                    out[y, x] = O
                    break
    return out


def shadow(a, cx=7.5, cy=14.7, rx=5.8, ry=1.6):
    """Ground shadow ellipse behind the feet (only on empty pixels)."""
    out = a.copy()
    h, w = a.shape
    for y in range(h):
        for x in range(w):
            if not out[y, x] and ((x + .5 - cx) / rx) ** 2 + ((y + .5 - cy) / ry) ** 2 <= 1:
                out[y, x] = SH
    return out


def recolor(a, swaps, rows=None):
    out = a.copy()
    sel = np.zeros_like(a, bool)
    if rows is None:
        sel[:] = True
    else:
        sel[rows[0]:rows[1]] = True
    for k, v in swaps.items():
        out[(a == LEGEND[k]) & sel] = LEGEND[v]
    return out


def compose(body, head, at, extra=None, cx=7.5):
    a = stamp(paint(body, 16), paint(head), *at)
    if extra is not None:
        a = extra(a)
    return shadow(outline(a), cx=cx)


