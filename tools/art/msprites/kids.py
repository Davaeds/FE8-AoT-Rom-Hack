def _dress(text, name):
    m = OUTFIT[name]
    return ''.join(m.get(c, c) for c in text)


def _build(name, upper, legs, view, at, cy=14.7):
    body = upper.strip('\n') + '\n' + legs.strip('\n')
    a = paint(_dress(body, name), 16)
    a = stamp(a, paint(KID_HEADS[name][view]), *at)
    return shadow(outline(a), cy=cy, rx=4.8, ry=1.4)


def frames(name):
    kind = 'skirt' if name == 'mikasa' else 'pants'
    out = {}
    for key, ups, legs in (('sms', SIDE_IDLE, SIDE_IDLE_LEGS), ('left', SIDE_RUN, SIDE_RUN_LEGS),
                           ('down', FRONT_WALK, FRONT_WALK_LEGS), ('sel', SEL, SEL_LEGS)):
        out[key] = [_build(name, u, l, v, at) for (u, v, at), l in zip(ups, legs[kind])]
    out['up'] = [_build(name, u, l, 'back', at) for (u, v, at), l in zip(FRONT_WALK, FRONT_WALK_LEGS[kind])]
    return out
