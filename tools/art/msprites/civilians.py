"""Shiganshina townsfolk and Carla Yeager: unarmed adults, 16x16."""
from kit import grid
from pal import LEGEND


def overlay(frame, text, dy=0):
    """Paint ASCII rows over a frame from row dy ('.' clears, ' ' keeps); the
    first line break after the opening quotes is not a row."""
    out = frame.copy()
    rows = text.split('\n')[1:] if text.startswith('\n') else text.split('\n')
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c != ' ' and 0 <= y + dy < out.shape[0] and x < out.shape[1]:
                out[y + dy, x] = LEGEND[c]
    return out


def _upper_shift(a, dy, split):
    """Move the rows above `split` by dy (the legs stay planted)."""
    out = a.copy()
    top = a[:split]
    out[:split] = 0
    if dy > 0:
        out[dy:split] = top[:split - dy]
    else:
        out[:split + dy] = top[-dy:]
    return out

