CLOTHES = {'townsman': {}, 'townswoman': {}, 'carla': {'G': 'B', 'n': 'b'}}
DRESS = {'townswoman', 'carla'}


def _join(top, legs):
    return grid(top.strip('\n') + '\n' + legs.strip('\n'))


def frames(name):
    head = HEADS[name]
    sw = CLOTHES[name]

    def mk(top, legs, view, dy=0):
        f = _join(top, legs)
        if name in DRESS:
            f = f.copy()
        for k, v in sw.items():
            m = f == LEGEND[k]; m[:8] = False
            f[m] = LEGEND[v]
        if view in head:
            f = overlay(f, head[view])
        return _upper_shift(f, dy, 12) if dy else f

    sl = DRESS_LEGS if name in DRESS else SIDE_LEGS
    fl = DRESS_FRONT if name in DRESS else FRONT_LEGS
    side = lambda l, dy=0: mk(SIDE_TOP, sl[l], 'side', dy)
    front = lambda l, dy=0: mk(FRONT_TOP, fl[l], 'front', dy)
    back = lambda l, dy=0: mk(BACK_TOP, fl[l], 'back', dy)
    sms = [side('stand'), side('stand', 1), side('stand', 1)]
    left = [side('stand'), side('pass', -1), side('stride'), side('pass', -1)]
    down = [front('stand'), front('stepL'), front('stand'), front('stepR')]
    up = [back('stand'), back('stepL'), back('stand'), back('stepR')]
    sel = [front('stand'), front('stand', 1), front('stand')]
    return dict(sms=sms, left=left, down=down, up=up, sel=sel)
